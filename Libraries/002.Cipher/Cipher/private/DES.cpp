DES::DES(uint64 key)
{
    makeRoundKeys(key);
}

uint64 DES::permute(uint64 num, const uint8* p, int inBits, 
    int outBits)
{
    uint64 out = 0;
    for (int i = 0; i < outBits; i++)
    {
        uint64 bit = num >> inBits - p[i] & 1;
        // num >> p[i] & 1 로 깔끔히 되도록 p 들을 대칭으로 수정해도
        // 되나 싶지만, DES 에서 제공하는 p 는 MSB 를 기준으로 하기에,
        // 그냥 제공하는 p값들을 쓰고, 위처럼 코드에서 대칭처리함

        out = (out << 1) | bit;
    }

    return out;
}





void DES::makeRoundKeys(uint64 key)
{
    key = permute(key, PC1, 64, 56);

    uint32 c = (key >> 28) & MASK_28;
    uint32 d = key & MASK_28;

    for (int i = 0; i < 16; i++)
    {
        ROL_28(c, SHIFTS[i]);
        ROL_28(d, SHIFTS[i]);

        uint64 val = (static_cast<uint64>(c) << 28) | d;


        roundKeys[i] = permute(val, PC2, 56, 48);
    }
}

void DES::ROL_28(uint32& shifter, uint32 n)
{
	shifter = (shifter << n | shifter >> 28 - n) & MASK_28;
}











uint64 DES::crypt(uint64 block, bool isDec)
{
    block = permute(block, IP, 64, 64); // IP 

    uint32 left = (block >> 32) & MASK_32;
    uint32 right = block & MASK_32;

    for (int r = 0; r < 16; r++)
    {
        uint64 temp = expandTo48(right); // (3)
        
        temp ^= isDec ? roundKeys[15 - r] : roundKeys[r]; // (4)

        uint32 tempRight = right;
        
        // (5 ) + (6)
        right = permuteAfterSubsitute(substitute(temp)) ^ left;
        left = tempRight;
    }

    // 마지막에 P-BOX 한번더
    block = (static_cast<uint64>(right) << 32) | left;


    //checkWehtherIP_FP_is_fine();
    return permute(block, FP, 64, 64); // FP ( IP 와 역치환 관계 )
}

uint64 DES::expandTo48(uint32 num)
{
    // 여긴 사실 permutation 이 아니라 32 비트가 4비트로 구성된 8개의 청크
    // 이고, 이 8개의 청크가 각각 인접한 청크들의 끝값을 하나씩 가져와,
    // 6비트의 청크가 8개이니 48비트로 확장되는 것. 
    // 고정된 인덱스만을 가져오니 이를 permute로 구현함
    // ※ 0번 청크의 left 는 7번 청크의 right. 7번의 right 는 0의 left
    return permute(num, E, 32, 48);
}

uint32 DES::substitute(uint64 num)
{
    uint32 out = 0;

    for (int i = 0; i < 8; i++)
    {
        int n = num >> (42 - i * 6) & MASK_6;
        // permute 에서 인덱스 좆같게 구한 것과 원인이 같다.
        // DES 에서 제공하는 S-BOX 에 맞춰, MSB 를 기준으로 처리하기에,
        // 인덱스가 위처럼 42 - i * 6 으로 좆같게 구해야 한다

        int row = (n >> 5 & 1) * 2 + (n & 1);
        int col = n >> 1 & MASK_4;

        out = (out << 4) | SBOX[i][row][col];
    }

    return out;
}

uint32 DES::permuteAfterSubsitute(uint32 num)
{
    return static_cast<uint32>(permute(num, P, 32, 32));
}






