ARIA::ARIA(const uint8* key, int keyBits)
{
    makeEncKeys(key, keyBits);
    makeDecKeys();
}
















void ARIA::crypt(uint8* m, uint8 keys[17][16])
{
    for (int r = 0; r < roundCount; ++r) // ※ 홀수번 반복해야 enc-dec 대칭 가능
    {
        xorBlock(m, keys[r]);
        if (r % 2 == 0)
        {
            substType1(m);
        }
        else 
        {
            substType2(m);
        }
        diffLayer(m);
    }

    xorBlock(m, keys[roundCount]);
    substType2(m);
    xorBlock(m, keys[roundCount + 1]);
}

void ARIA::makeDecKeys()
{
    memcpy(decKeys[0], encKeys[roundCount + 1], 16);
    for (int i = 1; i < roundCount + 1; ++i)
    {
        memcpy(decKeys[i], encKeys[roundCount - i + 1], 16);
        diffLayer(decKeys[i]);
    }
    memcpy(decKeys[roundCount + 1], encKeys[0], 16);
}




void ARIA::makeEncKeys(const uint8* key, int keyBits)
{
    // 코드만 길고 끔찍하다. 내용은 없다. XOR, 시프팅, 암복호화에 사용되는 
    // subst, diffLayer, xorBlock 을 사용해 난수들을 만들어 암호화 키를 만든다
    
    // ■ 라운드 수가 keyBytes에 따라 결정된다
    // 128 -> 11, 192 -> 13, 256 -> 15
    // encKeys[roundCount + 2][16]. 여유 있게 17
    

    static const uint8 CK[3][16] = {
    {0x51,0x7c,0xc1,0xb7,0x27,0x22,0x0a,0x94,0xfe,0x13,
    0xab,0xe8,0xfa,0x9a,0x6e,0xe0},
    {0x6d,0xb1,0x4a,0xcc,0x9e,0x21,0xc8,0x20,0xff,0x28,
    0xb1,0xd5,0xef,0x5d,0xe2,0xb0},
    {0xdb,0x92,0x37,0x1d,0x21,0x26,0xe9,0x70,0x03,0x24,
    0x97,0x75,0x04,0xe8,0xc9,0x0e}
    };

    auto FO = [](uint8* d, const uint8* rk) -> void
        {
            xorBlock(d, rk);
            substType1(d);
            diffLayer(d);
        };
    auto FE = [](uint8* d, const uint8* rk) -> void
        {
            xorBlock(d, rk);
            substType2(d);
            diffLayer(d);
        };
 

    assert(keyBits == 128 || keyBits == 192
        || keyBits == 256);

    roundCount = keyBits == 128 ? 11
        : keyBits == 192 ? 13
        : 15;
    int ci = keyBits == 128 ? 0
        : keyBits == 192 ? 1
        : 2;
    
    const uint8* c1 = CK[ci];
    const uint8* c2 = CK[(ci + 1) % 3];
    const uint8* c3 = CK[(ci + 2) % 3];

    uint8 W[4][16];
    uint8 KR[16] = { 0 };

    memcpy(W[0], key, 16);

    memcpy(KR, key + 16, (keyBits - 128) / 8); 
    // 잔여 할당. 나머지는 0 패딩

    memcpy(W[1], W[0], 16); FO(W[1], c1); xorBlock(W[1], KR);
    memcpy(W[2], W[1], 16); FE(W[2], c2); xorBlock(W[2], W[0]);
    memcpy(W[3], W[2], 16); FO(W[3], c3); xorBlock(W[3], W[1]);



    static const int rot[5] = { -19, -31, 61, 31, 19 };
    uint8 t[16];
    for (int g = 0; g < 5; ++g)
    {
        int cnt = (g == 4) ? 1 : 4;
        for (int j = 0; j < cnt; ++j)
        {
            int idx = g * 4 + j;
            int a = j;
            int b = (j + 1) % 4;
            if (j < 3)
            {
                if (rot[g] < 0)
                {
                    rotRight_128(t, W[b], -rot[g]);
                }
                else
                {
                    rotLeft_128(t, W[b], rot[g]);
                }
                memcpy(encKeys[idx], W[a], 16);
            }
            else
            {
                if (rot[g] < 0)
                {
                    rotRight_128(t, W[0], -rot[g]);
                }
                else
                {
                    rotLeft_128(t, W[0], rot[g]);
                }
                memcpy(encKeys[idx], W[3], 16);
            }

            xorBlock(encKeys[idx], t);
        }
    }
}



































void ARIA::substType1(uint8* state)
{
    for (int i = 0; i < 16; i += 4)
    {
        state[i] = S1[state[i]];
        state[i + 1] = S2[state[i + 1]];
        state[i + 2] = INV_S1[state[i + 2]];
        state[i + 3] = INV_S2[state[i + 3]];
    }
}

void ARIA::substType2(uint8* state)
{
    for (int i = 0; i < 16; i += 4)
    {
        state[i] = INV_S1[state[i]];
        state[i + 1] = INV_S2[state[i + 1]];
        state[i + 2] = S1[state[i + 2]];
        state[i + 3] = S2[state[i + 3]];
    }
}

void ARIA::diffLayer(uint8* x)
{
    // ■ diffLayer -> diffLayer = 0(원점)
    // 첫번째 diff 결과를 x -> y 라 하자. 두번째 diff(복호화) 결과를 y -> z 라 하자.
    // x[n] 을 드래그 후 Ctrl + F 를 해서 눈에 잘 띄게 한 후에, 직접 확인해보자.
    // z[0] 의 XOR 횟수 : 
    // x[0]-7, x[1]-2, x[2]-2, x[3]-2, x[4]-2, x[5]-4, x[6]-2, x[7]-4, 
    // x[8]-2, x[9]-2, x[10]-4, x[11]-4, x[12]-2, x[13]-4, x[14]-4, x[15]-2
    // 개가 나온다. 
    // 즉 z[n] 은 x[n] 이 홀수번 그 외의 x[i] 는 짝수번(2번 또는 4번이 나온다 함)이 나와, x[n] 만
    // 남는다 한다
    // (나머지 15 개의 z[n] 도 같은 방식으로 직접 검증할 수 있지만, 하고 싶지 않다)

    // ■ diffLayer함수의 선형성 
    // diffLayer 함수는 xor로만 연산되므로, 선형성을 가진다.
    // -> D(a^b) <-> D(a) ^ D(b)

    uint8 y[16];
    y[0] =  x[3] ^ x[4] ^ x[6] ^ x[8]   ^ x[9]  ^ x[13] ^ x[14];
    y[1] =  x[2] ^ x[5] ^ x[7] ^ x[8]   ^ x[9]  ^ x[12] ^ x[15];
    y[2] =  x[1] ^ x[4] ^ x[6] ^ x[10]  ^ x[11] ^ x[12] ^ x[15];
    y[3] =  x[0] ^ x[5] ^ x[7] ^ x[10]  ^ x[11] ^ x[13] ^ x[14];
    y[4] =  x[0] ^ x[2] ^ x[5] ^ x[8]   ^ x[11] ^ x[14] ^ x[15];
    y[5] =  x[1] ^ x[3] ^ x[4] ^ x[9]   ^ x[10] ^ x[14] ^ x[15];
    y[6] =  x[0] ^ x[2] ^ x[7] ^ x[9]   ^ x[10] ^ x[12] ^ x[13];
    y[7] =  x[1] ^ x[3] ^ x[6] ^ x[8]   ^ x[11] ^ x[12] ^ x[13];
    y[8] =  x[0] ^ x[1] ^ x[4] ^ x[7]   ^ x[10] ^ x[13] ^ x[15];
    y[9] =  x[0] ^ x[1] ^ x[5] ^ x[6]   ^ x[11] ^ x[12] ^ x[14];
    y[10] = x[2] ^ x[3] ^ x[5] ^ x[6]   ^ x[8]  ^ x[13] ^ x[15];
    y[11] = x[2] ^ x[3] ^ x[4] ^ x[7]   ^ x[9]  ^ x[12] ^ x[14];
    y[12] = x[1] ^ x[2] ^ x[6] ^ x[7]   ^ x[9]  ^ x[11] ^ x[12];
    y[13] = x[0] ^ x[3] ^ x[6] ^ x[7]   ^ x[8]  ^ x[10] ^ x[13];
    y[14] = x[0] ^ x[3] ^ x[4] ^ x[5]   ^ x[9]  ^ x[11] ^ x[14];
    y[15] = x[1] ^ x[2] ^ x[4] ^ x[5]   ^ x[8]  ^ x[10] ^ x[15];
    
    std::memcpy(x, y, 16);
}

void ARIA::xorBlock(uint8* a, const uint8* b)
{
    for (int i = 0; i < 16; ++i)
    {
        a[i] ^= b[i];
    }
}


uint8 ARIA::rotLeft_8(uint8 v, int n)
{
	assert(n <= 7 && n >= 0); // 검출용

	if (n)
	{
		return (uint8)((v << n) | (v >> (8 - n)));
	}
	return v;
}

void ARIA::rotRight_128(uint8* out, const uint8* in, int n)
{
    assert(n >= 0 && n <= 128); 
    
    // rotLeft_128 에서 n = 128 - 0 으로 호출할 수 있으니, 128 도 함께 처리함
    if (n == 0 || n == 128)
    {
        memcpy(out, in, 16);
        return;
    }

    int bs = n / 8; // 바이트 단위 시프팅
    int bt = n % 8; // 잔여 비트 단위 시프팅


    // hi : 바이트 시프팅 후 out[i] 에 위치할 바이트
    // lo : 바이트 스프팅 후 out[i-1] 에 위치할 바이트
    for (int i = 0; i < 16; ++i)
    {
        // ※ 바이트 시프팅
        uint8 hi = in[(i - bs + 16) % 16]; 
        uint8 lo = in[(i - bs - 1 + 32) % 16];

        // ※ 잔여 비트 시프팅
        out[i] = bt ? (uint8)((hi >> bt | (lo << (8 - bt)))) 
            : hi;
    }

    
}

void ARIA::rotLeft_128(uint8* out, const uint8* in, int n)
{
    assert(n >= 0 && n <= 127);

    rotRight_128(out, in, 128 - n);
}















































































































































