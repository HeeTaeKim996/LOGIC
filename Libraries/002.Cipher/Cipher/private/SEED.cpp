    auto func = [&](uint8* p, const uint8* c) -> void
        {
            SEED seed(key);

            uint8 temp[16];
            memcpy(temp, p, 16);

            seed.encrypt(temp);
            if (memcmp(temp, c, 16) != 0)
            {
                printf("암호화 실패\n");
                return;
            }

            seed.decrypt(temp);
            if (memcmp(temp, p, 16) != 0)
            {
                printf("복호화 실패\n");
                return;
            }

            printf("암복호화 성공\n");
        };

    func(pt, ct);
