SEED::SEED(const uint8* key)
{
    expandKeys(key);
}








void SEED::crypt(uint8* m, bool isDec)
{
    uint64 left = BigEndian::loadTo64(m);
    uint64 right = BigEndian::loadTo64(m + 8);

    for (int r = 0; r < 16; ++r)
    {
        const uint32* subKey = isDec ? subKeys[15 - r] : subKeys[r];

        uint64 tempRight = right;
        right = left ^ F(subKey, right);
        left = tempRight;
    }

    // right - left 를 한번 더 스왑 처리 
    // ( right 가 높은 차수, left 가 낮은 차수가 되도록 저장)
    BigEndian::storeFrom64(m,       right);
    BigEndian::storeFrom64(m + 8,   left);
}


uint64 SEED::F(const uint32 subKey[2], uint64 right)
{
    // 코드 볼 필요 없다. 섞는다.

    uint32 r0 = right >> 32;
    uint32 r1 = right & MASK_32;

    uint32 a = r0 ^ subKey[0];
    uint32 b = r1 ^ subKey[1];

    uint32 g1 = G(a ^ b);
    uint32 g2 = G(g1 + a);
    uint32 g3 = G(g1 + g2);

    return ((uint64)(g2 + g3) << 32) | g3;
}


uint32 SEED::G(uint32 x)
{
    // 코드 볼 필요 없다. 섞는다.

    uint8 y0 = S0[x & MASK_8];
    uint8 y1 = S1[(x >> 8) & MASK_8];
    uint8 y2 = S0[(x >> 16) & MASK_8];
    uint8 y3 = S1[x >> 24];

    const static uint8 m0 = 0xFC;
    const static uint8 m1 = 0xF3;
    const static uint8 m2 = 0xCF;
    const static uint8 m3 = 0x3F;

    uint8 z0 = (y0 & m0) ^ (y1 & m1) ^ (y2 & m2) ^ (y3 & m3);
    uint8 z1 = (y0 & m1) ^ (y1 & m2) ^ (y2 & m3) ^ (y3 & m0);
    uint8 z2 = (y0 & m2) ^ (y1 & m3) ^ (y2 & m0) ^ (y3 & m1);
    uint8 z3 = (y0 & m3) ^ (y1 & m0) ^ (y2 & m1) ^ (y3 & m2);

    return ((uint32)z3 << 24) | ((uint32)z2 << 16) 
        | ((uint32)z1 << 8) | z0;
}






















void SEED::expandKeys(const uint8* key) // 128 비트
{
    // 코드 볼필요 없다. 섞는다.

    uint32 k0 = BigEndian::loadTo32(key);
    uint32 k1 = BigEndian::loadTo32(key + 4);
    uint32 k2 = BigEndian::loadTo32(key + 8);
    uint32 k3 = BigEndian::loadTo32(key + 12);

    uint32 kc = 0x9E3779B9;

    for (int i = 0; i < 16; ++i)
    {
        subKeys[i][0] = G(k0 + k2 - kc);
        subKeys[i][1] = G(k1 - k3 + kc);

        if (i % 2 == 0)
        {
            uint64 v = ((uint64)k0 << 32) | k1;
            v = (v >> 8) | (v << 56);
            k0 = v >> 32;
            k1 = (uint32)v;
        }
        else
        {
            uint64 v = ((uint64)k2 << 32) | k3;
            v = (v << 8) | (v >> 56);
            k2 = v >> 32;
            k3 = (uint32)v;
        }

        kc = (kc << 1) | (kc >> 31);
    }
}






















