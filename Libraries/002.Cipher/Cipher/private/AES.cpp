AES::AES(const uint8* key, int keyBytes)
{
    assert(keyBytes == 16 || keyBytes == 24 || keyBytes == 32);

    keyExpansion(key, keyBytes);
}

void AES::encrypt(uint8* p)
{
    addRoundKey(p, 0);

    for (int r = 1; r < numberOfRounds; ++r)
    {
        subBytes(p);
        shiftRows(p);
        mixColumns(p);
        addRoundKey(p, r);
    }

    {
        subBytes(p);
        shiftRows(p);
        addRoundKey(p, numberOfRounds);
    }
}

void AES::decrypt(uint8* c)
{
    {
        addRoundKey(c, numberOfRounds);
        invShiftRows(c);
        invSubBytes(c);
    }

    for (int r = numberOfRounds - 1; r >= 1; --r)
    {
        addRoundKey(c, r);
        invMixColumns(c);
        invShiftRows(c);
        invSubBytes(c);
    }

    addRoundKey(c, 0);
}

void AES::subBytes(uint8* state)
{
    for (int i = 0; i < 16; ++i)
    {
        state[i] = SBOX[state[i]];
    }
}

void AES::invSubBytes(uint8* state)
{
    for (int i = 0; i < 16; ++i)
    {
        state[i] = INV_SBOX[state[i]];
    }
}





uint8 AES::gmul(uint8 a, uint8 b)
{
	uint8 res = 0;
	while (b)
	{
		if (b & 1) res ^= a;

		a = (a << 1) ^ ((a & 0x80) ? 0x1b : 0); 
        // 나머지 XOR 연산 을 multiplied a 에 미리 처리하여 성능 업
        // [ (a * b) % m == ( (a % m) * (b % m) ) % m ]

        // 이론적으로 m = 0x11b 이지만, 어차피 uint8 이기에 
        // 초과 비트가 절사되기에, 0x1b 사용
		
        b >>= 1;
	}

	return res;
}



void AES::mixColumns(uint8* state)
{
	for (int c = 0; c < 4; ++c) // 여기서 c 는 state 행렬의 col
	{        
        uint8* col = &state[c * 4];
        uint8 temp[4];

        for (int r = 0; r < 4; ++r) // 여기서 r은 MIX 행렬의 row
        {
            temp[r] = 0;
            for (int i = 0; i < 4; ++i)
            {
                temp[r] ^= gmul(col[i], MIX[r][i]);
            }
        }

        std::memcpy(col, temp, 4);
	}
}

void AES::invMixColumns(uint8* state) // MIX -> INV_MIX 외에 차이 없음
{
    for (int c = 0; c < 4; ++c) 
    {
        uint8* col = &state[c * 4];
        uint8 temp[4];

        for (int r = 0; r < 4; ++r) 
        {
            temp[r] = 0;
            for (int i = 0; i < 4; ++i)
            {
                temp[r] ^= gmul(col[i], INV_MIX[r][i]);// INV_MIX
            }
        }

        std::memcpy(col, temp, 4);
    }
}

void AES::shiftRows(uint8* state)
{
    uint8 temp[16];

    // state 매트릭스는 연산 때 오른쪽에 위치했으니,열우선 매트릭스임에 유의
    for (int c = 0; c < 4; ++c)
    {
        for (int r = 0; r < 4; ++r)
        {
            temp[c * 4 + r] = state[
                ((c + r) % 4) * 4 // 열 (새로운)
                    + r // 행

            // 행 r을 왼쪽으로 r 칸 : 새(r,c) 자리에 옛(r, c + r)
            ]; 
        }
    }

    std::memcpy(state, temp, 16);
}

void AES::invShiftRows(uint8* state) // shift 방향이 반대인 것 외 차이 없음
{
    uint8 temp[16];

    for (int c = 0; c < 4; ++c)
    {
        for (int r = 0; r < 4; ++r)
        {
            temp[c * 4 + r] = state[
                ((c - r + 4) % 4) * 4
                    + r
            ];
        }
    }

    std::memcpy(state, temp, 16);
}

void AES::addRoundKey(uint8* state, int round)
{
    for (int i = 0; i < 16; ++i)
    {
        state[i] ^= roundKeys[round][i];
    }
}


void AES::keyExpansion(const uint8* key, int keyBytes) // 16/24/32
{
    // 여기서 word 는 4바이트

    // 코드는 길지만 별거 없다. 초기값은 round0 의 키로 두되,
    // round 1 ~ 10/12/14 의 난수값들은 round0 값들부터 쭉 
    // XOR 해가며 난수들을 확장해나간 것.
    // 확장해나갈 때 wrodsCount 주기로 추가적인 치환 + 전치 가 있음.
    // 32(256)만 또 추가로 중간에 치환 이 있음

    const int wordsCount = keyBytes / 4; // 4/6/8
    numberOfRounds = wordsCount + 6; // 4->10, 6->12, 8->14
    const int expanedWordsCount = 4 * (numberOfRounds + 1); 
    // 44 / 52 / 60

    uint8 words[60][4]; // 여유있게 60까지 (4 는 word가 4byte 이므로)

    for (int i = 0; i < wordsCount; ++i)
    {
        std::memcpy(words[i], key + i * 4, 4);
    }

    uint8 rcon = 0x01;

    for (int i = wordsCount; i < expanedWordsCount; ++i)
    {
        uint8 temp[4];
        std::memcpy(temp, words[i - 1], 4);

        if (i % wordsCount == 0) 
            // 별거없다. wordsCount 주기로 특별하게 더 치환 + 전치
        {
            uint8 t0 = temp[0];
            temp[0] = temp[1];
            temp[1] = temp[2];
            temp[2] = temp[3];
            temp[3] = t0;

            for (int k = 0; k < 4; ++k)
            {
                temp[k] = SBOX[temp[k]];
            }

            temp[0] ^= rcon;
            rcon = gmul(rcon, 2);
        }
        else if (wordsCount > 6 && i % wordsCount == 4)
            // wrodsCount > 6 은 32(256) 밖에 없다.
            // 256 의 wrodCount = 8 이므로, == 4 는 중간에 한번 더 치환
        {
            for (int k = 0; k < 4; k++)
            {
                temp[k] = SBOX[temp[k]];
            }
        }

        for (int k = 0; k < 4; k++)
        {
            words[i][k] = words[i - wordsCount][k] ^ temp[k];
        }
    }

    for (int r = 0; r <= numberOfRounds; ++r)
    {
        std::memcpy(roundKeys[r], words[r * 4], 16);
    }
}


#include <functional>

using uint64 = unsigned long long;

void AES::test()
{

    const uint64 pt[2] = {
        0x7766554433221100ULL,
        0xffeeddccbbaa9988ULL
    };

    // 키는 00 01 02 ... 1f (32바이트), 앞에서 16/24/32바이트만 사용
    uint8 key[32];
    for (int i = 0; i < 32; ++i) key[i] = (uint8)i;

    const uint64 expected128[2] = {
        0x30047b6ad8e0c469ULL,
        0x5ac5b47080b7cdd8ULL
    };
    const uint64 expected192[2] = {
        0xe0df4c86a47ca9ddULL,
        0x91710deca070af6eULL
    };
    const uint64 expected256[2] = {
        0xbf456751cab7a28eULL,
        0x8960494b9049fceaULL
    };


    auto f = [&](const uint64* expected, uint8 len)
        -> void
        {
            printf("---\n");
            AES aes(key, len);
            
            uint64 buff[2];
            std::memcpy(buff, pt, 16);
            aes.encrypt(reinterpret_cast<uint8*>(buff));
            if (std::memcmp(buff, expected, 16) == 0)
            {
                printf("ENC 통과\n");
            }
            else
            {
                printf("ENC 실패\n");
            }

            aes.decrypt(reinterpret_cast<uint8*>(buff));
            if (std::memcmp(buff, pt, 16) == 0)
            {
                printf("DEC 통과\n");
            }
            else
            {
                printf("DEC 실패\n");
            }
        };

    f(expected128, 16);
    f(expected192, 24);
    f(expected256, 32);
}
